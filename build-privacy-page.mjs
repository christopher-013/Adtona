// Generates privacy.html from the privacy dialog in index.html.
//
// The dialog is the version travellers read, but a closed <dialog> is display:none and
// search engines discount it — so the ~500 words explaining what Adtona sends where were
// invisible to crawlers, and adtona.com had exactly one indexable URL. A standalone
// /privacy page fixes both, and gives the schema.org privacyPolicy property something
// real to point at.
//
// It is generated rather than hand-maintained so the two cannot drift: editing the dialog
// and forgetting the page would publish a privacy notice that no longer matches the app.
// privacy-page-smoke-test asserts the shipped file matches what this script produces.

import { readFileSync, writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";

// Exported so privacy-page-smoke-test can compare the checked-in file against a fresh
// render without shelling out and rewriting the working tree.
export function renderPrivacyPage() {
  const html = readFileSync("index.html", "utf8");
  const version = readFileSync("version.js", "utf8").match(/ADTONA_VERSION\s*=\s*"([^"]+)"/)?.[1];
  if (!version) throw new Error("version.js must define ADTONA_VERSION");

  const dialog = html.match(/<div class="info-dialog-body privacy-dialog-body">([\s\S]*?)<\/div>\s*<\/article>/)?.[1];
  if (!dialog) throw new Error("Could not find the privacy dialog body in index.html");

  // The dialog markup is already plain sections; only the heading levels shift, because on a
  // page of its own the privacy title is the h1 rather than a dialog label.
  const body = dialog
    .replace(/<h3>/g, "<h2>")
    .replace(/<\/h3>/g, "</h2>")
    .replace(/ class="info-dialog-lead"/, ' class="privacy-lead"')
    .replace(/ class="info-dialog-updated"/, ' class="privacy-updated"')
    .trim()
    .split("\n")
    .map((line) => (line.trim() ? `      ${line.trim()}` : ""))
    .join("\n");

  // script-src 'none': this page is static text and runs nothing, so it can be locked down
  // harder than the app itself.
  const page = `<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <meta name="theme-color" content="#f5f1e8">
  <meta name="referrer" content="no-referrer">
  <meta http-equiv="Content-Security-Policy" content="default-src 'self'; base-uri 'self'; object-src 'none'; form-action 'none'; script-src 'none'; style-src 'self'; img-src 'self'">
  <title>Privacy — Adtona</title>
  <meta name="description" content="What Adtona keeps in your browser, what it sends to Open-Meteo, Wikipedia, Wikivoyage, OpenStreetMap and Wikimedia Commons, and what its usage counting does and does not record.">
  <meta name="author" content="Adtona">
  <meta name="application-name" content="Adtona">
  <meta name="robots" content="index, follow, max-image-preview:large, max-snippet:-1">
  <link rel="canonical" href="https://adtona.com/privacy">
  <link rel="icon" href="/favicon.ico" sizes="16x16 32x32 48x48">
  <link rel="icon" type="image/png" sizes="32x32" href="/icons/favicon-32.png">
  <link rel="stylesheet" href="/privacy.css?v=${version}">
</head>
<body>
  <!-- Generated by build-privacy-page.mjs from the privacy dialog in index.html.
       Do not edit by hand: edit the dialog and re-run the script. -->
  <header class="privacy-header">
    <a class="privacy-home" href="/">
      <img src="/adtona-mark.png" alt="" width="34" height="34" decoding="async">
      <span><strong>Adtona</strong> — Plan the trip. Build the guide. Go Now.</span>
    </a>
  </header>
  <main class="privacy-card">
    <p class="privacy-eyebrow">Your privacy</p>
    <h1>Privacy</h1>
${body}
  </main>
  <footer class="privacy-footer">
    <p><a href="/">Back to Adtona</a> <span aria-hidden="true">·</span> <a href="https://www.instagram.com/adto.na/" target="_blank" rel="noopener noreferrer">Adtona on Instagram</a></p>
  </footer>
</body>
</html>
`;

  return page;
}

// Only write the file when run directly, so importing the renderer has no side effects.
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const page = renderPrivacyPage();
  writeFileSync("privacy.html", page);
  console.log(`Wrote privacy.html (${page.length} bytes) from the index.html privacy dialog.`);
}
